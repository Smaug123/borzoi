//! The frozen consumer fixtures (`docs/ast-versioning-plan.md` D6): one per
//! distinct published facade, at `crates/cst/tests/all/facade_consumers/`.
//!
//! A fixture is a consumer of the facade as it was frozen. It matches every
//! dispatch enum and value enum exhaustively, with no wildcard arm and every
//! payload's type spelled out, and calls every accessor with its result's
//! type spelled out. astgen writes it once, when the facade is published (or
//! re-baselined by a `FREEZE_EPOCH` bump), and never again;
//! `tools/ci/facade-lock-check.sh` refuses any edit to it. cst's test binary
//! compiles it, so a change that would break a consumer of a published facade
//! fails to build there, whatever the lock check let through.
//!
//! [`check_fixture`] holds a fixture to its facade's lock: it matches exactly
//! the lock's variants, names every dispatch enum and only types the lock
//! has, and calls only accessors the lock has. A lock may have node types and
//! accessors its fixture does not name: one appended after publication (an
//! allowed addition) is one the fixture never saw.

use std::collections::BTreeSet;

use crate::facade::Version;
use crate::lock::{EPOCH_MARK, Line, Lock, Payload};
use crate::shape::{Elem, Shape};
use crate::{reformat, screaming_snake};

/// The directory of the fixtures, repo-relative.
pub const FIXTURES_DIR: &str = "crates/cst/tests/all/facade_consumers";

/// The fixtures' module declarations, repo-relative.
pub const FIXTURES_MOD_PATH: &str = "crates/cst/tests/all/facade_consumers/mod.rs";

/// The fixture of the facade `module`, repo-relative.
pub fn fixture_path(module: &str) -> String {
    format!("{FIXTURES_DIR}/{module}.rs")
}

/// The fixtures' module declarations: one `mod` per published distinct
/// facade. Regenerated freely; the fixtures themselves are not.
pub fn generate_fixtures_mod(modules: &[String]) -> String {
    let mut out = String::from(
        "//! GENERATED by `tools/astgen` — do not edit by hand.\n\
         //! Regenerate with `cargo run -p borzoi-astgen --example generate`; kept honest\n\
         //! by borzoi-astgen's `tests/up_to_date.rs` staleness test.\n\
         //!\n\
         //! The frozen consumer fixtures of the published facades\n\
         //! (`docs/ast-versioning-plan.md` D6): one per distinct published facade,\n\
         //! written once, at its publication. Each compiles only while its facade\n\
         //! still offers every type, variant and accessor it had when it was frozen;\n\
         //! nothing in them runs.\n\n",
    );
    for module in modules {
        out.push_str(&format!("mod {module};\n"));
    }
    reformat(&out)
}

/// `TupleSegment` → `tuple_segment`.
fn snake(name: &str) -> String {
    screaming_snake(name).to_lowercase()
}

/// The Rust spelling of an element from outside the crate, the facade's types
/// under `f::`.
fn elem_type(e: &Elem) -> String {
    match e {
        Elem::Node(n) | Elem::Enum(n) | Elem::Value(n) => format!("f::{n}"),
        Elem::Token => "borzoi_cst::syntax::SyntaxToken".to_string(),
        Elem::Bool => "bool".to_string(),
        Elem::Usize => "usize".to_string(),
        Elem::I32 => "i32".to_string(),
        Elem::TextRange => "borzoi_cst::syntax::TextRange".to_string(),
        Elem::StaticStr => "&'static str".to_string(),
        Elem::Tuple(items) => {
            let items: Vec<String> = items.iter().map(elem_type).collect();
            format!("({})", items.join(", "))
        }
    }
}

/// The type a value of shape `s` is bound at, and the expression that turns
/// `expr` (a value of that shape) into it: an iterator is collected.
fn binding(s: &Shape, expr: &str) -> (String, String) {
    match s {
        Shape::One(e) => (elem_type(e), expr.to_string()),
        Shape::Option(e) => (format!("Option<{}>", elem_type(e)), expr.to_string()),
        Shape::Vec(e) => (format!("Vec<{}>", elem_type(e)), expr.to_string()),
        Shape::Iter(e) => (
            format!("Vec<{}>", elem_type(e)),
            format!("{expr}.collect()"),
        ),
    }
}

/// A derived trait's path from outside the crate.
fn trait_path(name: &str) -> String {
    match name {
        "Debug" => "std::fmt::Debug".to_string(),
        "Hash" => "std::hash::Hash".to_string(),
        other => other.to_string(),
    }
}

/// The frozen consumer fixture of the distinct facade `version`, whose lock
/// is `lock`, stamped with the freeze `epoch`.
pub fn generate_fixture(version: &Version, lock: &Lock, epoch: u32) -> String {
    let module = version.module();
    let names = lock.names();
    let mut out = format!(
        "//! FROZEN consumer fixture of the published `{module}` typed facade\n\
         //! (`docs/ast-versioning-plan.md` D6). `tools/astgen` wrote it when the facade\n\
         //! was published and never regenerates it; `tools/ci/facade-lock-check.sh`\n\
         //! refuses any edit to it. It is a consumer of the facade as it was frozen: it\n\
         //! matches every enum exhaustively, with no wildcard arm, and calls every\n\
         //! accessor with its result's type spelled out, so it stops compiling if the\n\
         //! facade loses or changes anything it had. Nothing in it runs.\n\
         //!\n\
         //! {EPOCH_MARK}{epoch}\n\n\
         #![allow(dead_code)]\n\n\
         use borzoi_cst::syntax::{module} as f;\n\n\
         /// What every node type and dispatch enum is.\n\
         fn handle<T: borzoi_cst::syntax::AstNode + std::fmt::Debug + Clone + PartialEq + Eq + \
         std::hash::Hash>() {{}}\n\n\
         /// The facade's root, read from a parse.\n\
         fn view(parse: &borzoi_cst::parser::Parse) -> Result<f::ParsedInput, \
         borzoi_cst::syntax::ViewError> {{\n\
         parse.view::<f::ParsedInput>()\n}}\n\n\
         fn handles() {{\n"
    );
    for name in names.nodes.iter().chain(&names.enums) {
        out.push_str(&format!("handle::<f::{name}>();\n"));
    }
    out.push_str("}\n\n");

    let mut current: Option<&str> = None;
    let close = |current: &mut Option<&str>, out: &mut String| {
        if current.take().is_some() {
            out.push_str("}\n}\n\n");
        }
    };
    for line in &lock.lines {
        if let Line::Enum {
            name,
            variant,
            node,
        } = line
        {
            if current != Some(name.as_str()) {
                close(&mut current, &mut out);
                out.push_str(&format!(
                    "fn enum_{}(value: f::{name}) {{\nmatch value {{\n",
                    snake(name)
                ));
                current = Some(name);
            }
            out.push_str(&format!(
                "f::{name}::{variant}(node) => {{\nlet _: f::{node} = node;\n}}\n"
            ));
        }
    }
    close(&mut current, &mut out);
    for line in &lock.lines {
        if let Line::Value {
            name,
            variant,
            payload,
        } = line
        {
            if current != Some(name.as_str()) {
                close(&mut current, &mut out);
                out.push_str(&format!(
                    "fn value_{}(value: f::{name}) {{\nmatch value {{\n",
                    snake(name)
                ));
                current = Some(name);
            }
            match payload {
                Payload::Unit => out.push_str(&format!("f::{name}::{variant} => {{}}\n")),
                Payload::Tuple(shapes) => {
                    let vars: Vec<String> = (0..shapes.len()).map(|i| format!("x{i}")).collect();
                    let lets: String = shapes
                        .iter()
                        .zip(&vars)
                        .map(|(s, v)| {
                            let (ty, expr) = binding(s, v);
                            format!("let _: {ty} = {expr};\n")
                        })
                        .collect();
                    out.push_str(&format!(
                        "f::{name}::{variant}({}) => {{\n{lets}}}\n",
                        vars.join(", ")
                    ));
                }
                Payload::Named(fields) => {
                    let names: Vec<&str> = fields.iter().map(|(f, _)| f.as_str()).collect();
                    let lets: String = fields
                        .iter()
                        .map(|(f, s)| {
                            let (ty, expr) = binding(s, f);
                            format!("let _: {ty} = {expr};\n")
                        })
                        .collect();
                    out.push_str(&format!(
                        "f::{name}::{variant} {{ {} }} => {{\n{lets}}}\n",
                        names.join(", ")
                    ));
                }
            }
        }
    }
    close(&mut current, &mut out);

    let mut derives: Vec<(&str, Vec<String>)> = Vec::new();
    for line in &lock.lines {
        if let Line::Derive { name, trait_ } = line {
            match derives.last_mut() {
                Some((n, traits)) if *n == name.as_str() => traits.push(trait_path(trait_)),
                _ => derives.push((name, vec![trait_path(trait_)])),
            }
        }
    }
    for (name, traits) in derives {
        out.push_str(&format!(
            "fn derives_{}() {{\nfn check<T: {}>() {{}}\ncheck::<f::{name}>();\n}}\n\n",
            snake(name),
            traits.join(" + ")
        ));
    }

    let mut owner: Option<&str> = None;
    for line in &lock.lines {
        if let Line::Accessor {
            owner: o,
            name,
            shape,
            ..
        } = line
        {
            if owner != Some(o.as_str()) {
                if owner.is_some() {
                    out.push_str("}\n\n");
                }
                out.push_str(&format!("fn node_{}(node: &f::{o}) {{\n", snake(o)));
                owner = Some(o);
            }
            let (ty, expr) = binding(shape, &format!("node.{name}()"));
            out.push_str(&format!("let _: {ty} = {expr};\n"));
        }
    }
    if owner.is_some() {
        out.push_str("}\n");
    }
    reformat(&out)
}

/// What a fixture's source exercises, read back with `syn`.
#[derive(Debug, Default)]
struct Exercised {
    /// `handle::<f::X>()`.
    handles: BTreeSet<String>,
    /// `(enum, variant)` arms of an `enum_*` function's match.
    enum_arms: BTreeSet<(String, String)>,
    /// `(value enum, variant)` arms of a `value_*` function's match.
    value_arms: BTreeSet<(String, String)>,
    /// `(owner, method)` called on a `node_*` function's `node`.
    accessors: BTreeSet<(String, String)>,
    /// Every way the fixture is not shaped as a generated one.
    errors: Vec<String>,
}

/// `f::A::B` → `["A", "B"]`, for a path through the facade alias.
fn facade_path(path: &syn::Path) -> Option<Vec<String>> {
    let segments: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    match segments.split_first() {
        Some((first, rest)) if first == "f" => Some(rest.to_vec()),
        _ => None,
    }
}

impl Exercised {
    fn read(file: &syn::File) -> Exercised {
        let mut ex = Exercised::default();
        for item in &file.items {
            let syn::Item::Fn(f) = item else { continue };
            let name = f.sig.ident.to_string();
            if name == "handles" {
                ex.read_handles(&f.block);
            } else if name.starts_with("enum_") || name.starts_with("value_") {
                let arms = if name.starts_with("enum_") {
                    &mut ex.enum_arms
                } else {
                    &mut ex.value_arms
                };
                let mut errors = Vec::new();
                read_match(&name, &f.block, arms, &mut errors);
                ex.errors.extend(errors);
            } else if name.starts_with("node_") {
                ex.read_accessors(&name, f);
            }
        }
        ex
    }

    fn read_handles(&mut self, block: &syn::Block) {
        for stmt in &block.stmts {
            let syn::Stmt::Expr(syn::Expr::Call(call), _) = stmt else {
                continue;
            };
            let syn::Expr::Path(func) = &*call.func else {
                continue;
            };
            let Some(last) = func.path.segments.last() else {
                continue;
            };
            let syn::PathArguments::AngleBracketed(args) = &last.arguments else {
                continue;
            };
            for arg in &args.args {
                if let syn::GenericArgument::Type(syn::Type::Path(ty)) = arg
                    && let Some([name]) = facade_path(&ty.path).as_deref()
                {
                    self.handles.insert(name.clone());
                }
            }
        }
    }

    fn read_accessors(&mut self, fn_name: &str, f: &syn::ItemFn) {
        let owner = f.sig.inputs.iter().find_map(|input| match input {
            syn::FnArg::Typed(pat) => match &*pat.ty {
                syn::Type::Reference(r) => match &*r.elem {
                    syn::Type::Path(p) => facade_path(&p.path).and_then(|s| match &s[..] {
                        [owner] => Some(owner.clone()),
                        _ => None,
                    }),
                    _ => None,
                },
                _ => None,
            },
            syn::FnArg::Receiver(_) => None,
        });
        let Some(owner) = owner else {
            self.errors
                .push(format!("`{fn_name}` takes no `&f::<Node>`"));
            return;
        };
        struct Calls<'a>(&'a str, &'a mut BTreeSet<(String, String)>);
        impl<'ast> syn::visit::Visit<'ast> for Calls<'_> {
            fn visit_expr_method_call(&mut self, call: &'ast syn::ExprMethodCall) {
                if let syn::Expr::Path(receiver) = &*call.receiver
                    && receiver.path.is_ident("node")
                {
                    self.1.insert((self.0.to_string(), call.method.to_string()));
                }
                syn::visit::visit_expr_method_call(self, call);
            }
        }
        syn::visit::Visit::visit_block(&mut Calls(&owner, &mut self.accessors), &f.block);
    }
}

/// Collect the arms of the one `match` in `block` as `(type, variant)`,
/// refusing any arm that is not `f::Type::Variant…` or has a guard.
fn read_match(
    fn_name: &str,
    block: &syn::Block,
    arms: &mut BTreeSet<(String, String)>,
    errors: &mut Vec<String>,
) {
    let matched = block.stmts.iter().find_map(|stmt| match stmt {
        syn::Stmt::Expr(syn::Expr::Match(m), _) => Some(m),
        _ => None,
    });
    let Some(matched) = matched else {
        errors.push(format!("`{fn_name}` has no match"));
        return;
    };
    for arm in &matched.arms {
        let path = match &arm.pat {
            syn::Pat::TupleStruct(p) => Some(&p.path),
            syn::Pat::Struct(p) => Some(&p.path),
            syn::Pat::Path(p) => Some(&p.path),
            _ => None,
        };
        match path.and_then(facade_path).as_deref() {
            Some([ty, variant]) if arm.guard.is_none() => {
                arms.insert((ty.clone(), variant.clone()));
            }
            _ => errors.push(format!(
                "`{fn_name}` has an arm that is not one `f::Type::Variant` without a guard \
                 (a wildcard, a binding or an alternative)"
            )),
        }
    }
}

/// Every way the fixture `text` fails to be the frozen consumer of the facade
/// `module`, whose lock is `lock`, stamped with the freeze `epoch`.
pub fn check_fixture(module: &str, lock: &Lock, epoch: Option<u32>, text: &str) -> Vec<String> {
    let mut errors = Vec::new();
    let stamp = text.lines().find_map(|l| {
        l.strip_prefix("//!")
            .map(str::trim_start)
            .and_then(|l| l.strip_prefix(EPOCH_MARK))
    });
    let stamped = stamp.and_then(|s| s.parse::<u32>().ok());
    if stamped != epoch {
        errors.push(format!(
            "the fixture is stamped at freeze epoch {stamped:?}, its lock at {epoch:?}"
        ));
    }
    let file = match syn::parse_file(text) {
        Ok(file) => file,
        Err(e) => {
            errors.push(format!("the fixture does not parse: {e}"));
            return errors;
        }
    };
    let ex = Exercised::read(&file);
    errors.extend(ex.errors.iter().cloned());
    let names = lock.names();
    // The fixture names every type it was frozen with. A node type may have
    // been added to the lock since (an allowed addition), so it may name
    // fewer nodes than the lock; it names every dispatch enum, since no
    // enum is ever added, and nothing the lock lacks.
    let types: BTreeSet<String> = names.nodes.iter().chain(&names.enums).cloned().collect();
    let beyond: Vec<_> = ex.handles.difference(&types).collect();
    let missing_enums: Vec<_> = names.enums.difference(&ex.handles).collect();
    if !beyond.is_empty() || !missing_enums.is_empty() {
        errors.push(format!(
            "the fixture's `handles` names {beyond:?} beyond the lock, and misses the \
             dispatch enums {missing_enums:?}"
        ));
    }
    let mut enum_arms = BTreeSet::new();
    let mut value_arms = BTreeSet::new();
    let mut accessors = BTreeSet::new();
    for line in &lock.lines {
        match line {
            Line::Enum { name, variant, .. } => {
                enum_arms.insert((name.clone(), variant.clone()));
            }
            Line::Value { name, variant, .. } => {
                value_arms.insert((name.clone(), variant.clone()));
            }
            Line::Accessor { owner, name, .. } => {
                accessors.insert((owner.clone(), name.clone()));
            }
            _ => {}
        }
    }
    for (what, fixture, locked) in [
        ("dispatch-enum", &ex.enum_arms, &enum_arms),
        ("value-enum", &ex.value_arms, &value_arms),
    ] {
        if fixture != locked {
            errors.push(format!(
                "the fixture's {what} arms differ from the lock's variants: it matches \
                 {:?} beyond them and misses {:?}",
                fixture.difference(locked).collect::<Vec<_>>(),
                locked.difference(fixture).collect::<Vec<_>>()
            ));
        }
    }
    let extra: Vec<_> = ex.accessors.difference(&accessors).collect();
    if !extra.is_empty() {
        errors.push(format!(
            "the fixture calls accessors the lock lacks: {extra:?}"
        ));
    }
    if ex.accessors.is_empty() {
        errors.push(format!("the `{module}` fixture calls no accessor"));
    }
    errors
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::facade::{self, versions};
    use crate::features;

    /// A fixture generated from a lock passes the check against it, and the
    /// check notices a dropped arm, a wildcard, a missing handle, a call the
    /// lock lacks and a stale stamp.
    #[test]
    fn a_generated_fixture_covers_its_lock() {
        let rows = features::feature_table();
        let union = crate::union_lock();
        let version = versions()[5];
        let lock = facade::derived_lock(&union, &rows, version.decimal);
        let text = generate_fixture(&version, &lock, 3);
        assert_eq!(
            check_fixture("v8", &lock, Some(3), &text),
            Vec::<String>::new()
        );
        for (from, to, needle) in [
            (
                "f::Type::Paren(node) => {\n            let _: f::ParenType = node;\n        }\n",
                "_ => {}\n",
                "not one `f::Type::Variant`",
            ),
            (
                "f::Type::Paren(node) => {\n            let _: f::ParenType = node;\n        }\n",
                "",
                "misses [(\"Type\", \"Paren\")]",
            ),
            (
                "    handle::<f::Type>();\n",
                "",
                "misses the dispatch enums [\"Type\"]",
            ),
            (
                "let _: Option<f::Type> = node.inner();",
                "let _: Option<f::Type> = node.inner();\nlet _ = node.no_such_accessor();",
                "no_such_accessor",
            ),
            (
                "freeze-epoch: 3",
                "freeze-epoch: 2",
                "stamped at freeze epoch",
            ),
        ] {
            assert!(text.contains(from), "the fixture has no {from:?}");
            let broken = text.replacen(from, to, 1);
            let errors = check_fixture("v8", &lock, Some(3), &broken).join("\n");
            assert!(errors.contains(needle), "{needle:?} not in:\n{errors}");
        }
    }

    /// A frozen fixture keeps covering its lock through every addition the
    /// freeze allows (`facade::is_allowed_addition`): one line of each such
    /// tag, appended to the lock it was generated from, leaves the check clean.
    #[test]
    fn every_allowed_addition_keeps_the_fixture_covering() {
        let rows = features::feature_table();
        let union = crate::union_lock();
        let version = versions()[5];
        let lock = facade::derived_lock(&union, &rows, version.decimal);
        let text = generate_fixture(&version, &lock, 1);
        let s = String::from;
        let additions = [
            Line::Node {
                node: s("FreshNode"),
                kind: s("FRESH_NODE"),
            },
            Line::Node {
                node: s("ParenType"),
                kind: s("FRESH_PAREN_TYPE"),
            },
            Line::Derive {
                name: s("TupleSegment"),
                trait_: s("Ord"),
            },
            Line::Accessor {
                owner: s("ParenType"),
                name: s("fresh"),
                shape: Shape::One(Elem::Bool),
                delegate: Some(s("fresh")),
            },
        ];
        let tags: BTreeSet<String> = additions
            .iter()
            .filter_map(|l| l.render().split('\t').next().map(String::from))
            .collect();
        assert_eq!(
            tags,
            ["accessor", "derive", "node"].map(String::from).into()
        );
        for line in additions {
            assert!(facade::is_allowed_addition(&line), "{line:?}");
            let mut grown = lock.clone();
            grown.lines.insert(line.clone());
            assert!(grown.check().is_empty(), "{line:?}: {:?}", grown.check());
            assert_eq!(
                check_fixture("v8", &grown, Some(1), &text),
                Vec::<String>::new(),
                "{line:?}"
            );
        }
    }
}
