//! The cst corpus gates' manifest vocabulary: where each sweep's checked-in
//! [`Manifest`] lives and the one command that regenerates it.
//!
//! Every per-file entry starts with the corpus-relative, `/`-separated path
//! ([`corpus_relative`]), then the file's bucket, so a [`Manifest`] diff — which is
//! sorted — puts a file's old and new lines next to each other. A sweep's
//! dominant bucket is one summary entry carrying its count, spelled with a
//! leading `(` so it sorts ahead of every path.

use std::path::{Path, PathBuf};

pub use borzoi_oracle_harness::corpus_key::{corpus_relative, sort_by_corpus_key};
use borzoi_oracle_harness::manifest::{Manifest, UPDATE_ENV, check};

/// Set by `tools/cst-grid-base.sh` to the directory a recovery grid writes its
/// base file into ([`check_no_worse_than_base`]).
const GRID_BASE_OUT_ENV: &str = "BORZOI_GRID_BASE_OUT";

/// The checked-in manifest for the sweep `name`.
pub fn manifest_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/manifests")
        .join(format!("{name}.txt"))
}

/// The command that regenerates the manifest of the `#[ignore]`d sweep in case
/// group `group`.
pub fn regenerate_ignored(group: &str) -> String {
    format!(
        "{UPDATE_ENV}=1 nix develop -c cargo test -p borzoi-cst --test all {group}:: -- --ignored"
    )
}

/// Compare `actual` against the checked-in manifest of sweep `name`.
#[track_caller]
pub fn check_manifest(name: &str, actual: &Manifest, regenerate: &str) {
    check(&manifest_path(name), actual, regenerate);
}

/// The summary entry for a sweep's dominant bucket: `(<bucket>) <count> files`.
pub fn summary_entry(bucket: &str, count: usize) -> String {
    format!("({bucket}) {count} files")
}

/// The base file of recovery grid `name`: the grid's divergences under the
/// parser on `main` when `tools/cst-grid-base.sh` last ran.
fn base_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/manifests")
        .join(format!("{name}.base.txt"))
}

/// A recovery grid must not diverge from FCS on any cell where the base
/// parser agrees with it: every key in `divergent` (a cell, or a cell and the
/// declaration it grades, spelled the same under any parser) must be in the
/// grid's base file. Unlike [`check_manifest`], no environment variable
/// rewrites the base from this branch's parser; `tools/cst-grid-base.sh`
/// regenerates it from `main`'s, so a cell this branch makes worse stays red
/// until the parser is fixed.
///
/// With [`GRID_BASE_OUT_ENV`] set (by that script, running these tests over
/// `main`'s parser), writes `divergent` to that directory instead.
#[track_caller]
pub fn check_no_worse_than_base(name: &str, divergent: &[String]) {
    let actual = Manifest::from_entries(divergent.iter().cloned()).expect("one key per line");
    if let Some(dir) = std::env::var_os(GRID_BASE_OUT_ENV) {
        let path = Path::new(&dir).join(format!("{name}.base.txt"));
        std::fs::write(
            &path,
            actual.render(
                "Generated by tools/cst-grid-base.sh; do not edit by hand.\n\
                 The grid's divergences under the parser on `main`, one key per line.",
            ),
        )
        .unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        return;
    }
    let path = base_path(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "no base file at {} ({e}). Generate it with: bash tools/cst-grid-base.sh",
            path.display()
        )
    });
    let base = Manifest::parse(&text)
        .unwrap_or_else(|(line, e)| panic!("{} is malformed at line {line}: {e}", path.display()));
    let base: std::collections::BTreeSet<&str> =
        base.entries().iter().map(String::as_str).collect();
    let worse: Vec<&str> = actual
        .entries()
        .iter()
        .map(String::as_str)
        .filter(|k| !base.contains(k))
        .collect();
    assert!(
        worse.is_empty(),
        "{} cells of `{name}` diverge from FCS where `main`'s parser agrees with it:\n{}",
        worse.len(),
        worse.join("\n")
    );
}
