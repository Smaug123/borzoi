//! Anonymous record types (`TType_anon`, `u_ty` tag 9) in F# signature data.
//!
//! An anonymous record anywhere in a signature pickles a `TType_anon` whose
//! `AnonRecdTypeInfo` is declared inline into the pickle's fourth OSGN table
//! (`ianoninfos`). A reader that cannot decode it loses every F# overlay for
//! the whole assembly, as FsCheck 3.3.2 did. Each position fsc can pickle one
//! in is compiled once and diffed against `fcs-dump entities`; the decoded
//! anon-info table is then held to what the source declares.
//!
//! fsc also compiles each anonymous record type to a public class
//! (`<>f__AnonymousType…`) that no pickled entity describes, so FCS, reading
//! the assembly through its pickle, lists none of them, while through IL it
//! lists them all.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

use borzoi_assembly::fsharp_pickle::model::PickledType;
use borzoi_assembly::test_support::NormalisedAssembly;
use borzoi_assembly::{
    Ecma335Assembly, EcmaView, Entity, Member, MemberMeasures, ResourceKind, ValFacts, ValMeasures,
    unpickle_signature,
};

use crate::common::{
    ArgGroupObligation, Lang, assert_dll_projections_agree, compile_generated,
    compile_generated_without_interface_data, diff_il_imported_dll,
};

/// Every place a signature can mention an anonymous record: a module value
/// and function, parameters and returns, record, union-case and exception
/// fields, class members, an abbreviation, a generic instantiation, nesting,
/// and the struct form. Then one only a function body mentions, which has a
/// class but no pickled info.
const ANON_SOURCE: &str =
    "// Generated by crates/assembly/tests/all/fsharp_anon_records.rs — do not edit.
namespace Generated

type R0 = { Shape: {| B: string; A: int |} }

type U0 =
    | Holds of {| A: int |}
    | Empty

exception E0 of {| Code: int |}

type AnonAlias = {| Alias: bool |}

type C0() =
    member _.Get () : {| A: int; B: string |} = Unchecked.defaultof<_>
    member _.Prop : struct {| S: int |} = Unchecked.defaultof<_>
    static member Take (x: {| A: int |}) : int = x.A

module Anon =
    let value : {| A: int; B: string |} = {| A = 1; B = \"b\" |}
    let structValue : struct {| S: int |} = struct {| S = 1 |}
    let nested : {| Outer: {| Inner: int |} |} = {| Outer = {| Inner = 1 |} |}
    let generic (x: 'a) : {| Item: 'a |} = {| Item = x |}
    let inList : {| A: int |} list = []
    let take (x: {| A: int |}) (y: AnonAlias) : int = x.A
    let bodyOnly () : int = {| Hidden = 1 |}.Hidden
";

/// A type declared in source under a name fsc gives an anonymous record's
/// class, in the global namespace where fsc puts them. It is a pickled entity.
const NAMESAKE_SOURCE: &str = "
namespace global

[<CompiledName(\"<>f__AnonymousType7`0\")>]
type Namesake() =
    member _.X = 1
";

/// The anon-record field sets the signatures in [`ANON_SOURCE`] mention,
/// sorted as FCS sorts them, each with whether it is the struct form.
fn declared_infos() -> BTreeSet<(Vec<&'static str>, bool)> {
    [
        (vec!["A", "B"], false),
        (vec!["A"], false),
        (vec!["Code"], false),
        (vec!["Alias"], false),
        (vec!["S"], true),
        (vec!["Outer"], false),
        (vec!["Inner"], false),
        (vec!["Item"], false),
    ]
    .into_iter()
    .collect()
}

/// Compiled once: the content-addressed build directory is not safe for two
/// concurrent builds of one source.
fn compiled() -> &'static Path {
    static BUILT: OnceLock<PathBuf> = OnceLock::new();
    BUILT.get_or_init(|| {
        let source = format!("{ANON_SOURCE}{NAMESAKE_SOURCE}");
        compile_generated(Lang::FSharp, &source)
            .unwrap_or_else(|e| panic!("compile: {e}\n--- source ---\n{source}"))
    })
}

/// The projected entities named as fsc names an anonymous record's class.
fn anon_class_names(ours: &NormalisedAssembly) -> Vec<&str> {
    ours.entities
        .iter()
        .map(|e| e.fqn.as_str())
        .filter(|fqn| fqn.starts_with("<>f__AnonymousType"))
        .collect()
}

/// The projection reads the signature data whole (the differential fails on
/// any skipped overlay) and agrees with FCS: of the classes named like an
/// anonymous record's, only the one declared in source is listed, under its
/// source name.
#[test]
fn anon_record_signatures_agree_with_fcs() {
    let agreed = assert_dll_projections_agree(compiled(), ArgGroupObligation::ModulesCommit);
    assert_eq!(anon_class_names(&agreed.ours), Vec::<&str>::new());
    assert!(agreed.ours.entities.iter().any(|e| e.fqn == "Namesake"));
}

/// Through IL, FCS lists every generated class, and so does the projection.
#[test]
fn anon_record_classes_are_listed_without_interface_data() {
    const SOURCE: &str =
        "// Generated by crates/assembly/tests/all/fsharp_anon_records.rs — do not edit.
namespace Generated

module Anon =
    let value : {| A: int; B: string |} = {| A = 1; B = \"b\" |}
    let structValue : struct {| S: int |} = struct {| S = 1 |}
    let nested : {| Outer: {| Inner: int |} |} = {| Outer = {| Inner = 1 |} |}
    let generic (x: 'a) : {| Item: 'a |} = {| Item = x |}
    let bodyOnly () : int = {| Hidden = 1 |}.Hidden
";
    let dll = compile_generated_without_interface_data(SOURCE)
        .unwrap_or_else(|e| panic!("compile: {e}\n--- source ---\n{SOURCE}"));
    let agreed = diff_il_imported_dll(&dll).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(
        anon_class_names(&agreed.ours).len(),
        6,
        "one class per anon type"
    );
}

/// The decoded anon-info table is exactly the field sets the source declares,
/// with the struct flag, and every `TType_anon` names a slot in it. Agreement
/// with FCS cannot see this: no projected fact reads the info yet.
#[test]
fn anon_record_infos_decode_as_declared() {
    let bytes = std::fs::read(compiled()).expect("read the compiled fixture");
    let view = Ecma335Assembly::parse(&bytes).expect("parse the compiled fixture");
    let resources = view.fsharp_resources().expect("F# resources");
    let payload = |kinds: &[ResourceKind]| {
        resources
            .iter()
            .find(|r| kinds.contains(&r.kind))
            .map(|r| r.payload.as_slice())
    };
    let primary = payload(&[
        ResourceKind::SignatureData,
        ResourceKind::SignatureCompressedData,
    ])
    .expect("a signature resource");
    let stream_b = payload(&[
        ResourceKind::SignatureDataB,
        ResourceKind::SignatureCompressedDataB,
    ]);
    let ccu = unpickle_signature(primary, stream_b).expect("the signature unpickles");

    let infos = &ccu.tables.anoninfos;
    assert_eq!(infos.len(), ccu.header.nanoninfos as usize);
    let decoded: BTreeSet<(Vec<&str>, bool)> = infos
        .iter()
        .map(|info| {
            let names = info.sorted_ids.iter().map(|id| id.name.as_str()).collect();
            (names, info.is_struct)
        })
        .collect();
    assert_eq!(
        decoded.len(),
        infos.len(),
        "one slot per distinct anon type"
    );
    assert_eq!(decoded, declared_infos());
    for info in infos {
        let ccu_name = &ccu.header.ccu_refs[info.ccu as usize].name;
        assert_eq!(
            ccu_name, "Generated",
            "every anon type here is declared here"
        );
    }

    // Every val whose type mentions an anon record decodes to a `TType_anon`
    // naming one of those slots, with one type argument per field.
    fn anons(ty: &PickledType, out: &mut Vec<(u32, usize)>) {
        match ty {
            PickledType::Anon { info, args } => {
                out.push((*info, args.len()));
                args.iter().for_each(|a| anons(a, out));
            }
            PickledType::App { args, .. }
            | PickledType::Tuple { elems: args, .. }
            | PickledType::UCase { args, .. } => args.iter().for_each(|a| anons(a, out)),
            PickledType::Fun { domain, range, .. } => {
                anons(domain, out);
                anons(range, out);
            }
            PickledType::Forall { body, .. } => anons(body, out),
            PickledType::AppSimple { .. } | PickledType::Var { .. } | PickledType::Measure(_) => {}
        }
    }
    let mut seen = Vec::new();
    for val in &ccu.tables.vals {
        anons(&val.ty, &mut seen);
    }
    assert!(
        seen.len() >= 7,
        "the module's vals alone mention anon records seven times: {seen:?}"
    );
    for (info, arity) in seen {
        assert_eq!(infos[info as usize].sorted_ids.len(), arity);
    }
}

/// A unit of measure in an anonymous record's field is a measure in the
/// signature: IL erases it from the class's type argument as from any other.
/// `fcs-dump` renders such a type unerased, so this is pinned without it.
#[test]
fn a_measure_in_an_anon_record_field_is_read() {
    const SOURCE: &str =
        "// Generated by crates/assembly/tests/all/fsharp_anon_records.rs — do not edit.
namespace Generated

[<Measure>] type m

module Fns =
    let measured (x: {| D: float<m> |}) : int = 0
    let plain (x: {| D: float |}) : int = 0

type Measured() =
    member _.M (x: {| D: float<m> |}) : int = 0

type Plain() =
    member _.M (x: {| D: float |}) : int = 0
";
    let dll = compile_generated(Lang::FSharp, SOURCE)
        .unwrap_or_else(|e| panic!("compile: {e}\n--- source ---\n{SOURCE}"));
    let bytes = std::fs::read(dll).expect("read the compiled fixture");
    let view = Ecma335Assembly::parse(&bytes).expect("parse the compiled fixture");
    let (entities, skips) = view.enumerate_type_defs_with_skips().expect("enumerate");
    assert!(!skips.fsharp_signature_non_authoritative, "{skips:#?}");
    let entity = |name: &str| -> &Entity {
        entities
            .iter()
            .find(|e| e.name == name)
            .unwrap_or_else(|| panic!("{name} is projected"))
    };
    let measures = |name: &str| -> ValMeasures {
        let method = entity("Fns")
            .members
            .iter()
            .find_map(|m| match m {
                Member::Method(m) if m.name == name => Some(m),
                _ => None,
            })
            .unwrap_or_else(|| panic!("Fns.{name} is projected"));
        match &method.val_facts {
            ValFacts::Read(facts) => facts.measures.clone(),
            other => panic!("Fns.{name}'s val is read: {other:?}"),
        }
    };
    assert_eq!(measures("measured"), ValMeasures::Measured);
    assert!(matches!(
        measures("plain"),
        ValMeasures::NoDirectMeasure { .. }
    ));
    assert_eq!(entity("Measured").member_measures, MemberMeasures::Measured);
    assert!(matches!(
        entity("Plain").member_measures,
        MemberMeasures::NoDirectMeasure { .. }
    ));
}
